#!/usr/bin/env node
/**
 * Renders `src/theme/tokens.ts` into `src/theme/tokens.css`: the token
 * custom properties on `:root` (the default variant), a block per complete
 * variant keyed on the `data-zd-mode` / `data-zd-brand` attributes, and one
 * Tailwind `@utility` per token. Run `pnpm gen:tokens` after editing the
 * table; `--check` exits 1 when the committed CSS is stale (the test does
 * the same).
 *
 * Plain JavaScript on purpose: Node strips the types from the imported table
 * itself, so no TypeScript runner is needed.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  DEFAULT_THEME_VARIANT,
  THEME_VARIANTS,
  TOKEN_ROLES,
  isThemeVariantComplete,
  themeTokens,
} from '../src/theme/tokens.ts'
import tailwindConfig from '../tailwind.config.ts'

/** Palette colour names: `zd:bg-<name>` etc. already exist for each. */
const PALETTE = new Set(Object.keys(tailwindConfig.theme?.extend?.colors ?? {}))

const OUT_URL = new URL('../src/theme/tokens.css', import.meta.url)

const HEADER = `/* GENERATED by scripts/gen-tokens.mjs from src/theme/tokens.ts. Do not edit:
   change the table and run \`pnpm gen:tokens\`. tokens.test.ts fails when this
   file is stale.

   Semantic colour tokens. The custom properties on :root carry the default
   variant, ${DEFAULT_THEME_VARIANT.mode}/${DEFAULT_THEME_VARIANT.brand}. Each
   complete variant follows as a block keyed on the data-zd-mode and
   data-zd-brand attributes (Screen writes them from its \`theme\` prop; a host
   may set them on any ancestor). data-zd-mode="system" takes the light
   values and, under prefers-color-scheme: dark, the dark ones. The blocks
   sit in :where() so they carry no specificity: a host rule on the same
   element wins, and inline overrides win over everything. Each @utility
   reads one token, so a component writes \`zd:bg-neutral-primary\` and never
   a value. Values carry their own alpha, so the utilities take no opacity
   modifier. Unlayered like the rest of the stylesheet (see styles.css). */
`

/** The declarations block for one variant: `--zd-<token>: <value>;` lines. */
export function renderVariantDeclarations(variant, tokens = themeTokens, indent = '') {
  const column = THEME_VARIANTS.findIndex(
    (v) => v.mode === variant.mode && v.brand === variant.brand,
  )
  if (column < 0) throw new Error(`Unknown theme variant ${JSON.stringify(variant)}`)
  const lines = []
  for (const [name, values] of Object.entries(tokens)) {
    const value = values[column]
    if (value === null) {
      throw new Error(
        `Token ${name} has no value for ${variant.mode}/${variant.brand}; fill it in before emitting that variant`,
      )
    }
    lines.push(`${indent}  --zd-${name}: ${value};`)
  }
  return lines.join('\n')
}

/** The variants every token states a value for: the ones the stylesheet carries. */
export function completeVariants(tokens = themeTokens) {
  return THEME_VARIANTS.filter((v) =>
    isThemeVariantComplete(v.mode, v.brand, tokens),
  )
}

/**
 * One variant's block, keyed on the attributes. `modeAttribute` lets the
 * `system` setting reuse a variant's values under its own attribute value.
 */
export function renderVariantBlock(
  variant,
  tokens = themeTokens,
  { modeAttribute = variant.mode, indent = '' } = {},
) {
  const selector = `:where([data-zd-mode="${modeAttribute}"][data-zd-brand="${variant.brand}"])`
  return [
    `${indent}${selector} {`,
    `${indent}  color-scheme: ${variant.mode};`,
    renderVariantDeclarations(variant, tokens, indent),
    `${indent}}`,
  ].join('\n')
}

/** The attribute-keyed blocks for every complete variant, plus `system`. */
export function renderVariantBlocks(tokens = themeTokens) {
  const blocks = []
  for (const variant of completeVariants(tokens)) {
    blocks.push(renderVariantBlock(variant, tokens))
    if (variant.mode === 'light') {
      blocks.push(renderVariantBlock(variant, tokens, { modeAttribute: 'system' }))
    } else {
      blocks.push(
        `@media (prefers-color-scheme: dark) {\n${renderVariantBlock(variant, tokens, { modeAttribute: 'system', indent: '  ' })}\n}`,
      )
    }
  }
  return blocks.join('\n\n')
}

/** The whole stylesheet: default-variant properties plus the utilities. */
export function renderTokensCss(tokens = themeTokens) {
  const utilities = Object.keys(tokens).map((name) => {
    const role = name.slice(0, name.indexOf('-'))
    const property = TOKEN_ROLES[role]
    if (!property) throw new Error(`Token ${name} has no known role prefix`)
    const tail = name.slice(name.indexOf('-') + 1)
    if (PALETTE.has(tail)) {
      throw new Error(`Token ${name} shadows the palette colour ${tail}`)
    }
    return `@utility ${name} {\n  ${property}: var(--zd-${name});\n}`
  })
  return `${HEADER}\n:root {\n${renderVariantDeclarations(DEFAULT_THEME_VARIANT, tokens)}\n}\n\n${renderVariantBlocks(tokens)}\n\n${utilities.join('\n')}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = renderTokensCss()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT_URL, 'utf8')
    } catch {}
    if (current !== css) {
      console.error('src/theme/tokens.css is stale: run `pnpm gen:tokens`')
      process.exit(1)
    }
    console.log('src/theme/tokens.css is up to date')
  } else {
    writeFileSync(OUT_URL, css)
    console.log(`wrote ${fileURLToPath(OUT_URL)}`)
  }
}
